    private const string NetworkPreparationScript = """
        wifi_connection_uuid = None
        wifi_secrets = set()

        def command_error_detail(error):
            if isinstance(error, subprocess.CalledProcessError):
                detail = (error.stderr or error.stdout or '').strip()
                detail = detail or 'Command failed with exit code %s: %s' % (error.returncode, error.cmd)
            else:
                detail = str(error)
            for secret in wifi_secrets:
                detail = detail.replace(secret, '[redacted]')
            return detail

        def network_command(*args, timeout=60):
            return subprocess.run(list(args), check=True, capture_output=True, text=True, timeout=timeout).stdout

        def scan_wifi():
            network_command('nmcli', 'networking', 'on')
            network_command('nmcli', 'radio', 'wifi', 'on')
            output = network_command('nmcli', '--escape', 'no', '-t', '-f', 'SSID,SECURITY', 'device', 'wifi', 'list', '--rescan', 'yes', timeout=30)
            networks = {}
            for line in output.splitlines():
                ssid, separator, security = line.rpartition(':')
                if separator and ssid:
                    networks.setdefault(ssid, set()).add(security)
            return networks

        def wifi_key_management(security):
            personal = [value for value in security if '802.1X' not in value]
            if any('WPA1' in value or 'WPA2' in value for value in personal):
                return 'wpa-psk'
            if any('WPA3' in value for value in personal):
                return 'sae'
            if any('802.1X' in value or 'WEP' in value for value in security):
                raise RuntimeError('This network needs enterprise or WEP authentication, which this connection dialog does not support. Choose another network or use Ethernet.')
            return 'wpa-psk'

        def write_wifi_profile(connection, keyfile):
            fd = os.open(connection, os.O_CREAT | os.O_TRUNC | os.O_WRONLY, 0o600)
            os.fchmod(fd,0o600)
            with os.fdopen(fd,'w') as stream:
                stream.write(keyfile.to_data()[0])

        def connect_wifi(wifi, networks=None):
            step('Connecting the selected Wi-Fi network')
            global wifi_connection_uuid
            if wifi['Password']:
                wifi_secrets.add(wifi['Password'])
            if networks is None:
                networks = scan_wifi()
            from gi.repository import GLib
            import uuid
            keyfile = GLib.KeyFile()
            if wifi_connection_uuid is None:
                wifi_connection_uuid = str(uuid.uuid4())
            connection_uuid = wifi_connection_uuid
            for section, name, value in [('connection','id','Win2Linux Wi-Fi'),('connection','uuid',connection_uuid),('connection','type','wifi'),('wifi','mode','infrastructure'),('wifi','ssid',wifi['Ssid']),('ipv4','method','auto'),('ipv6','method','auto')]:
                keyfile.set_string(section,name,value)
            # Activate explicitly so a failed profile cannot trigger background password prompts.
            keyfile.set_boolean('connection','autoconnect',False)
            if not wifi['IsOpenNetwork']:
                keyfile.set_string('wifi-security','key-mgmt',wifi_key_management(networks.get(wifi['Ssid'], set())))
                keyfile.set_string('wifi-security','psk',wifi['Password'])
                keyfile.set_integer('wifi-security','psk-flags',0)
            pathlib.Path('/run/NetworkManager/system-connections').mkdir(parents=True, exist_ok=True, mode=0o700)
            connection = '/run/NetworkManager/system-connections/win2linux-wifi.nmconnection'
            write_wifi_profile(connection, keyfile)
            loaded = False
            try:
                network_command('nmcli','connection','load',connection)
                loaded = True
                network_command('nmcli','--wait','45','connection','up','uuid',connection_uuid)
                keyfile.set_boolean('connection','autoconnect',True)
                write_wifi_profile(connection, keyfile)
                network_command('nmcli','connection','load',connection)
            except (OSError, subprocess.SubprocessError):
                pathlib.Path(connection).unlink(missing_ok=True)
                if loaded:
                    try:
                        subprocess.run(['nmcli','--wait','5','connection','delete','uuid',connection_uuid], capture_output=True, text=True, timeout=10)
                    except (OSError, subprocess.SubprocessError):
                        pass
                raise
            step('Wi-Fi connection activated')

        def network_dialog(*args, text):
            # Passwords are returned through stdout, never placed in process arguments or logs.
            result = subprocess.run(['zenity', '--text=' + html.escape(text), *args], capture_output=True, text=True)
            if result.returncode == 1:
                return None
            if result.returncode != 0:
                raise RuntimeError('The network dialog could not open: ' + result.stderr.strip())
            return result.stdout.removesuffix('\n')

        def connect_wifi_from_dialog():
            networks = scan_wifi()
            names = sorted(networks)
            if not names:
                raise RuntimeError('No Wi-Fi networks were detected. Check the Wi-Fi hardware switch, move closer to the router, or connect Ethernet and retry.')
            ssid = network_dialog('--list', '--title=Connect to Wi-Fi', '--width=650', '--height=360',
                                  '--column=Network', '--ok-label=Next', '--cancel-label=Back', '--', *names,
                                  text='Select the Wi-Fi network to use during installation.')
            if not ssid:
                return False
            security = networks[ssid]
            is_open = bool(security) and all(value in ('', '--') for value in security)
            password = None
            if not is_open:
                wifi_key_management(security)
                password = network_dialog('--entry', '--hide-text', '--title=Wi-Fi password', '--width=650',
                                          '--ok-label=Connect', '--cancel-label=Back',
                                          text='Enter the password for ' + ssid + '.')
                if password is None:
                    return False
                if not password:
                    raise RuntimeError('A password is required for this secured Wi-Fi network.')
            connect_wifi(dict(Ssid=ssid, Password=password, IsOpenNetwork=is_open), networks)
            return True

        def check_download_connection(archive_url):
            step('Checking access to the selected kernel archive' if '/stonking/' in archive_url else 'Checking the download connection')
            with urllib.request.urlopen(archive_url, timeout=30):
                pass
            step('Download connection verified')

        def recover_network(error, archive_url, phase, wifi_connected):
            if not shutil.which('zenity'):
                raise error
            while True:
                step('Waiting for an installer network connection')
                detail = command_error_detail(error)
                print('Win2Linux: %s error: %s: %s' % (phase, type(error).__name__, detail), flush=True)
                if phase == 'download':
                    status = 'Wi-Fi was connected, but the download check failed. You can retry the download check without entering the password again.' if wifi_connected else 'The download connection is not ready. Connect to Wi-Fi here, or plug in Ethernet and retry.'
                    actions = ['Retry download check', 'Change Wi-Fi network' if wifi_connected else 'Connect to Wi-Fi']
                else:
                    status = 'The Wi-Fi connection failed. NetworkManager reported the error below. You can try connecting again, or plug in Ethernet and retry.'
                    actions = ['Connect to Wi-Fi', 'Retry connection']
                action = network_dialog('--list', '--title=Internet connection needed', '--width=720', '--height=320',
                    '--column=Action', '--ok-label=Continue', '--cancel-label=Stop', '--',
                    *actions, text=status + '\n\nPartitioning has not started.\n\nConnection error: ' + detail)
                if action is None:
                    raise RuntimeError('Network setup was stopped before partitioning.')
                attempt = 'download'
                try:
                    if action in ('Connect to Wi-Fi', 'Change Wi-Fi network'):
                        attempt = 'wifi'
                        if not connect_wifi_from_dialog():
                            continue
                        wifi_connected = True
                    elif action not in ('Retry connection', 'Retry download check'):
                        continue
                    attempt = 'download'
                    check_download_connection(archive_url)
                    return
                except (OSError, subprocess.SubprocessError, ImportError, RuntimeError) as caught:
                    error = caught
                    phase = attempt
                    if phase == 'wifi':
                        wifi_connected = False

        def prepare_network(wifi, kernel73):
            archive_url = 'https://archive.ubuntu.com/ubuntu/dists/' + ('stonking' if kernel73 else 'noble') + '/Release'
            phase = 'wifi'
            wifi_connected = False
            try:
                if wifi:
                    connect_wifi(wifi)
                    wifi_connected = True
                phase = 'download'
                if kernel73:
                    check_download_connection(archive_url)
            except (OSError, subprocess.SubprocessError, ImportError, RuntimeError) as error:
                recover_network(error, archive_url, phase, wifi_connected)
        """;

    private static string PrepareScript(List<PartitionInfo> parts, Guid espGuid, bool kernel73, WifiNetworkConfiguration? wifi)
    {
        var expected = JsonSerializer.Serialize(parts.Select(p => new {
            number = p.PartitionNumber, offset = p.OffsetBytes, size = p.SizeBytes,
            type = Guid.Parse(p.GptType!).ToString("D"), uuid = p.Guid?.Trim('{', '}').ToLowerInvariant()
        }));
        var hook = """
            #!/bin/sh
            set -e
            . /lib/partman/lib/base.sh
            target=$(cat /tmp/win2linux/disk)
            esp=$(cat /tmp/win2linux/esp)
            found=0
            for dev in "$DEVICES"/*; do
                [ -d "$dev" ] || continue
                cd "$dev"
                open_dialog PARTITIONS
                while { read_line num id size type fs path name; [ "$id" ]; }; do
                    # Only the staged ESP may be mounted as /boot/efi.
                    if [ "$path" = "$esp" ] && [ "$(cat device)" = "$target" ]; then
                        mkdir -p "$id"
                        echo efi > "$id/method"
                        rm -f "$id/format"
                        found=$((found + 1))
                    elif [ -f "$id/method" ] && [ "$(cat "$id/method")" = efi ]; then
                        echo keep > "$id/method"
                        rm -f "$id/mountpoint" "$id/format"
                    fi
                done
                close_dialog
            done
            [ "$found" = 1 ] || { echo 'Win2Linux: could not isolate the staged ESP' >&2; exit 1; }
            """;
        var commitHook = """
            #!/bin/sh
            set -e
            . /lib/partman/lib/base.sh
            : > /tmp/win2linux/planned.tsv
            for dev in "$DEVICES"/*; do
                [ -d "$dev" ] || continue
                cd "$dev"
                disk=$(cat device)
                open_dialog PARTITIONS
                while { read_line num id size type fs path name; [ "$id" ]; }; do
                    [ "$fs" = free ] && continue
                    method=$(cat "$id/method" 2>/dev/null || true)
                    mountpoint=$(cat "$id/mountpoint" 2>/dev/null || true)
                    format=no; [ ! -f "$id/format" ] || format=yes
                    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$disk" "$id" "$size" "$path" "$fs" "$method" "$format" "$mountpoint" >> /tmp/win2linux/planned.tsv
                done
                close_dialog
            done
            python3 /tmp/win2linux/prepare.py --check-plan
            """;
        return $$"""
            import html, json, os, pathlib, shutil, subprocess, sys, urllib.request
            stage = 'Starting preparation'
            def step(message):
                global stage
                stage = message
                print('Win2Linux: ' + message, flush=True)
            def report_error(error_type, error, traceback):
                # Omit source lines, which can contain the saved Wi-Fi credentials.
                print('Win2Linux: %s failed: %s: %s' % (stage, error_type.__name__, command_error_detail(error)), file=sys.stderr, flush=True)
            sys.excepthook = report_error
            def run(*args):
                return subprocess.check_output(args, text=True).strip()
            {{NetworkPreparationScript}}
            if sys.argv[1:] == ['--check-plan']:
                step('Checking the installer partition plan')
                snapshot = json.loads(pathlib.Path('/tmp/win2linux/preserved.json').read_text())
                planned = {}
                roots = []
                for line in pathlib.Path('/tmp/win2linux/planned.tsv').read_text().splitlines():
                    device, extent, size, node, fs, method, format_flag, mountpoint = line.split('\t')
                    start, end = map(int, extent.split('-'))
                    assert node not in planned, 'Duplicate planned partition'
                    planned[node] = (device, start, int(size), method, format_flag, mountpoint)
                    if mountpoint == '/':
                        roots.append(node)
                for device, saved in snapshot['tables'].items():
                    for part in saved['partitions']:
                        node = part['node']
                        assert node in planned, 'Installer would delete a preserved partition: ' + node
                        dev, start, size, method, format_flag, mountpoint = planned.pop(node)
                        assert dev == device and start == part['start'] * saved['sectorsize'] and size == part['size'] * saved['sectorsize'], 'Installer would resize or move a preserved partition: ' + node
                        assert format_flag == 'no' and mountpoint != '/', 'Installer would format a preserved partition: ' + node
                        assert method in ('', 'keep', 'efi') and (method != 'efi' or node == snapshot['esp']), 'Installer would modify a protected filesystem: ' + node
                if len(planned) != 1 or len(roots) != 1 or roots[0] not in planned:
                    new_parts = ', '.join('%s (mount=%s, method=%s, format=%s)' % (node, item[5], item[3], item[4]) for node, item in planned.items()) or 'none'
                    raise AssertionError('Installer must create exactly one new root partition; roots=%s; new partitions=%s' % (roots, new_parts))
                device, start, size, method, format_flag, mountpoint = planned[roots[0]]
                assert device == snapshot['disk'] and start >= snapshot['free_start'] and start + size <= snapshot['free_end'], 'Installer root is outside the reserved free space'
                assert method == 'format' and format_flag == 'yes' and mountpoint == '/', 'Invalid root partition plan'
                print('Win2Linux: partition plan preserves all existing partitions')
                sys.exit(0)
            step('Waiting for block devices')
            if subprocess.run(['udevadm', 'settle', '--timeout=10']).returncode:
                print('Win2Linux: udev settle timed out; checking the staged ESP directly', flush=True)
            step('Resolving the staged ESP by PARTUUID')
            esp = os.path.realpath('/dev/disk/by-partuuid/{{espGuid:D}}')
            assert pathlib.Path(esp).is_block_device(), 'Staged ESP GUID was not found'
            assert run('blkid', '-s', 'TYPE', '-o', 'value', esp) == 'vfat', 'ESP must be FAT'
            parent = run('lsblk', '-nro', 'PKNAME', esp)
            assert parent and '/' not in parent and '\n' not in parent, 'Ambiguous ESP parent'
            disk = '/dev/' + parent
            assert run('lsblk', '-dnro', 'TYPE', disk) == 'disk', 'Target is not a disk'
            print('Win2Linux: target disk resolved to', disk, 'ESP:', esp, flush=True)
            step('Verifying the target GPT and preserved partition geometry')
            table = json.loads(run('sfdisk', '--json', disk))['partitiontable']
            assert table['label'] == 'gpt', 'Target must use GPT'
            expected = json.loads({{JsonSerializer.Serialize(expected)}})
            actual = table['partitions']
            sector = table['sectorsize']
            assert len(actual) == len(expected), 'Target partition count changed since Windows staging'
            for entry in expected:
                suffix = ('p' if disk[-1].isdigit() else '') + str(entry['number'])
                match = next((p for p in actual if p['node'] == disk + suffix), None)
                assert match is not None, 'Expected target partition was not found: ' + disk + suffix
                assert match['start'] * sector == entry['offset'], 'Preserved partition offset changed'
                assert match['size'] * sector == entry['size'], 'Preserved partition size changed'
                assert match['type'].lower() == entry['type'], 'Preserved GPT type changed'
                if entry['uuid']:
                    assert match.get('uuid', '').lower() == entry['uuid'], 'Preserved partition GUID changed'
            esp_entry = next((p for p in actual if p.get('uuid', '').lower() == '{{espGuid:D}}'), None)
            assert esp_entry is not None, 'Staged ESP GUID was not found in the target GPT'
            step('Checking the reserved Linux free space')
            last_end = max(p['start'] + p['size'] for p in actual)
            assert last_end == esp_entry['start'] + esp_entry['size'], 'ESP must precede Linux free space'
            trailing = table['lastlba'] + 1 - last_end
            assert trailing * sector >= 20 * 1024**3, 'Insufficient trailing Linux space'
            previous = table['firstlba']
            for part in sorted(actual, key=lambda p: p['start']):
                assert part['start'] - previous < trailing, 'Largest free extent is not the staged Linux space'
                previous = part['start'] + part['size']
            wifi = json.loads({{JsonSerializer.Serialize(JsonSerializer.Serialize(wifi))}})
            prepare_network(wifi, {{(kernel73 ? "True" : "False")}})
            # A connection dialog can stay open while devices are disconnected or changed.
            step('Rechecking the verified target disk')
            assert os.path.realpath('/dev/disk/by-partuuid/{{espGuid:D}}') == esp and pathlib.Path(esp).is_block_device(), 'Staged ESP changed during network setup'
            assert run('lsblk', '-nro', 'PKNAME', esp) == parent, 'Target disk changed during network setup'
            assert json.loads(run('sfdisk', '--json', disk))['partitiontable'] == table, 'Target partition table changed during network setup'
            pathlib.Path('/tmp/win2linux/disk').write_text(disk)
            pathlib.Path('/tmp/win2linux/esp').write_text(esp)
            step('Saving preservation snapshots for attached disks')
            tables = {}
            for device in json.loads(run('lsblk', '-Jd', '-o', 'PATH,TYPE'))['blockdevices']:
                if device['type'] != 'disk':
                    continue
                saved = json.loads(run('sfdisk', '--json', device['path']))['partitiontable']
                assert saved['label'] == 'gpt', 'Attached disk %s uses %s; preservation checks currently require GPT' % (device['path'], saved['label'])
                tables[device['path']] = saved
            pathlib.Path('/tmp/win2linux/preserved.json').write_text(json.dumps(dict(tables=tables, disk=disk, esp=esp, free_start=last_end*sector, free_end=(table['lastlba']+1)*sector)))
            step('Installing partition preservation hooks')
            hook = pathlib.Path('/lib/partman/init.d/51win2linux-efi')
            hook.write_text({{JsonSerializer.Serialize(hook.Replace("\r\n", "\n"))}})
            hook.chmod(0o755)
            commit_hook = pathlib.Path('/lib/partman/commit.d/00win2linux-preserve')
            commit_hook.write_text({{JsonSerializer.Serialize(commitHook.Replace("\r\n", "\n"))}})
            commit_hook.chmod(0o755)
            print('Win2Linux: Ubiquity target verified:', disk, 'ESP:', esp)
            """;
    }

    private static string FinishScript(LinuxSetupConfiguration config, Guid espGuid)
    {
        var targetScript = $$"""
            #!/bin/bash
            set -euo pipefail
            export DEBIAN_FRONTEND=noninteractive
            apt-get update
            {{(config.KernelSelection == "linux-7.3-legion" ? KernelArchiveScript : "# Use Zorin's kernel tooling")}}
            apt-get install -y --no-install-recommends os-prober ca-certificates ubuntu-drivers-common
            {{(config.KernelSelection == "linux-7.3-legion" ? KernelScript(config.InstallNvidiaDrivers) : config.InstallNvidiaDrivers ? "ubuntu-drivers install" : "# No proprietary GPU driver requested")}}
            {{(config.InstallProprietaryCodecs ? "apt-get install -y --no-install-recommends ubuntu-restricted-addons" : "# No extra codecs requested")}}
            printf '0.0 0 0\n0\nLOCAL\n' > /etc/adjtime
            sed -i '/^#\?GRUB_DISABLE_OS_PROBER/d' /etc/default/grub
            printf '\nGRUB_DISABLE_OS_PROBER=false\n' >> /etc/default/grub
            update-grub
            mkdir -p /usr/local/sbin /var/lib/win2linux
            cat > /usr/local/sbin/win2linux-cleanup <<'WIN2LINUX_CLEANUP'
            #!/bin/sh
            set -eu
            source=$(findmnt -nro SOURCE /boot/efi)
            test "$(blkid -s PARTUUID -o value "$source")" = '{{espGuid:D}}'
            test -s /boot/efi/EFI/ubuntu/grub.cfg
            mkdir -p /boot/efi/EFI/boot
            cp /boot/efi/EFI/ubuntu/grub.cfg /boot/efi/EFI/boot/grub.cfg
            cp /boot/efi/EFI/ubuntu/grubx64.efi /boot/efi/EFI/boot/grubx64.efi
            cp /boot/efi/EFI/ubuntu/shimx64.efi /boot/efi/EFI/boot/bootx64.efi
            rm -rf /boot/efi/win2linux /boot/efi/casper /boot/efi/.disk /boot/efi/boot /boot/efi/dists /boot/efi/pool
            systemctl disable win2linux-cleanup.service
            WIN2LINUX_CLEANUP
            chmod 0755 /usr/local/sbin/win2linux-cleanup
            cat > /etc/systemd/system/win2linux-cleanup.service <<'WIN2LINUX_SERVICE'
            [Unit]
            Description=Win2Linux installer staging cleanup
            After=local-fs.target
            RequiresMountsFor=/boot/efi
            [Service]
            Type=oneshot
            ExecStart=/usr/local/sbin/win2linux-cleanup
            [Install]
            WantedBy=multi-user.target
            WIN2LINUX_SERVICE
            systemctl enable win2linux-cleanup.service
            touch /var/lib/win2linux/zorin-install-complete
            """;
        return $$"""
            #!/bin/bash
            set -euo pipefail
            # Ubiquity has already unmounted these by success_command time.
            mounted=()
            cleanup_mounts() {
                for ((i=${#mounted[@]}-1;i>=0;i--)); do umount -R "${mounted[i]}" || true; done
            }
            trap cleanup_mounts EXIT
            for name in dev proc sys; do
                mkdir -p "/target/$name"
                if ! mountpoint -q "/target/$name"; then
                    mount --rbind "/$name" "/target/$name"
                    mount --make-rslave "/target/$name"
                    mounted+=("/target/$name")
                fi
            done
            if [ -f /run/NetworkManager/system-connections/win2linux-wifi.nmconnection ]; then
                install -D -m 0600 /run/NetworkManager/system-connections/win2linux-wifi.nmconnection /target/etc/NetworkManager/system-connections/win2linux-wifi.nmconnection
            fi
            {{Decode(targetScript, "/target/tmp/win2linux-finish.sh")}}
            if chroot /target /bin/bash /tmp/win2linux-finish.sh 2>&1 | tee /target/var/log/win2linux-zorin-setup.log; then
                rm -f /target/tmp/win2linux-finish.sh
                {{(!config.InteractiveReview ? "systemd-run --unit=win2linux-reboot --on-active=30s /usr/bin/systemctl reboot" : "# Leave the completion dialog open for review")}}
            else
                # Keep the live session open when the requested kernel/driver setup fails.
                echo 'Win2Linux: Zorin post-install setup failed; see /target/var/log/win2linux-zorin-setup.log' >&2
                if command -v zenity >/dev/null; then
                    zenity --error --text='Zorin was installed, but the requested kernel or driver setup failed. See /target/var/log/win2linux-zorin-setup.log before restarting.' || true
                fi
                exit 1
            fi
            """;
    }

