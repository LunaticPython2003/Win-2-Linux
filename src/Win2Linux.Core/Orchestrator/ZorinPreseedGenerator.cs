/// <summary>Ubiquity configuration with a GUID-resolved disk and a preserved installer ESP.</summary>
internal static class ZorinPreseedGenerator
{
    public static string Generate(InstallationPlan plan, int espNumber, ulong espSize,
        string? espGuid, ulong? espOffset, string passwordHash, IDictionary<string, string>? scripts = null)
    {
        SafetyValidator.AssertNotProtectedSystemDisk(plan.Target.DiskNumber, plan.Target.DiskGuid,
            plan.Target.WindowsDiskSerial, plan.ProtectedDisk);
        SafetyValidator.AssertNotSystemVolume(plan.Target.DriveLetter, plan.ProtectedDisk);
        if (!Guid.TryParse(espGuid, out var guid) || espNumber <= 0 || espSize == 0 || espOffset is null or 0)
            throw new InvalidOperationException("Zorin requires the verified staged ESP GUID and byte geometry.");
        var parts = plan.Target.Partitions.Where(p => p.PartitionNumber != espNumber)
            .Append(new PartitionInfo(plan.Target.DiskNumber, espNumber, null, espSize,
                "c12a7328-f81f-11d2-ba4b-00a0c93ec93b", guid.ToString("D"), espOffset)).ToList();
        if (parts.Any(p => p.OffsetBytes is null or 0 || p.SizeBytes == 0 || !Guid.TryParse(p.GptType, out _)) ||
            parts.Select(p => p.PartitionNumber).Distinct().Count() != parts.Count)
            throw new InvalidOperationException("Zorin requires verified geometry and GPT types for every preserved partition.");
        var ordered = parts.OrderBy(p => p.OffsetBytes).ToList();
        ulong end = 0;
        foreach (var part in ordered)
        {
            if (part.OffsetBytes!.Value < end || part.OffsetBytes.Value > ulong.MaxValue - part.SizeBytes)
                throw new InvalidOperationException("Zorin target partition geometry overlaps or overflows.");
            end = part.OffsetBytes.Value + part.SizeBytes;
        }
        if (ordered[^1].PartitionNumber != espNumber)
            throw new InvalidOperationException("Zorin requires its staged ESP immediately before the unallocated Linux space.");

        var config = plan.EffectiveSetupConfig;
        if (config.KernelSelection is not "linux-default" and not "linux-7.3-legion")
            throw new InvalidOperationException("Zorin supports its distribution kernel or the signed Ubuntu 7.3 kernel.");
        if (config.WifiNetwork is { } wifi &&
            (string.IsNullOrWhiteSpace(wifi.Ssid) || (!wifi.IsOpenNetwork && string.IsNullOrEmpty(wifi.Password))))
            throw new InvalidOperationException("Zorin Wi-Fi requires an SSID and a saved key for secured networks.");
        if (scripts != null)
        {
            scripts["early.sh"] = EarlyScript;
            scripts["prepare.py"] = PrepareScript(parts, guid, config.KernelSelection == "linux-7.3-legion", config.WifiNetwork);
            scripts["finish.sh"] = FinishScript(config, guid);
        }
        var early = "bash /cdrom/win2linux/unattended/early.sh";
        var success = "bash /cdrom/win2linux/unattended/finish.sh";

        // A single physical line per command is required by debconf's preseed parser.
        return $$"""
            # Zorin OS Ubiquity preseed, generated by Win2Linux
            d-i debian-installer/locale string {{Line(config.Locale)}}
            d-i console-setup/ask_detect boolean false
            d-i keyboard-configuration/layoutcode string {{Line(config.KeyboardLayout)}}
            d-i netcfg/get_hostname string {{Line(config.Hostname)}}
            d-i time/zone string {{Line(config.Timezone)}}
            d-i clock-setup/utc boolean false
            d-i passwd/user-fullname string {{Line(config.RealName)}}
            d-i passwd/username string {{Line(config.Username)}}
            d-i passwd/user-password-crypted password {{passwordHash}}
            d-i user-setup/allow-password-weak boolean false
            d-i user-setup/encrypt-home boolean false
            d-i partman/early_command string {{early}}
            d-i partman-auto/disk string /dev/win2linux-target-unverified
            # Do not set partman-auto/method: method + disk makes Ubiquity erase that disk.
            d-i partman-auto/init_automatically_partition select biggest_free
            d-i partman-auto/choose_recipe select win2linux
            d-i partman-auto/expert_recipe string win2linux :: 256 256 256 fat32 $iflabel{ gpt } $reusemethod{ } method{ efi } . 20480 10000 -1 ext4 $primary{ } method{ format } format{ } use_filesystem{ } filesystem{ ext4 } mountpoint{ / } .
            d-i partman/choose_partition select finish
            d-i partman/confirm boolean true
            d-i partman/confirm_nooverwrite boolean true
            d-i partman-basicfilesystems/no_swap boolean false
            d-i grub-installer/only_debian boolean false
            d-i grub-installer/with_other_os boolean true
            d-i grub-installer/bootdev string /dev/win2linux-target-unverified
            ubiquity ubiquity/download_updates boolean false
            ubiquity ubiquity/use_nonfree boolean false
            ubiquity ubiquity/reboot boolean false
            ubiquity ubiquity/success_command string {{success}}
            """;
    }

    private static string Line(string value)
    {
        if (value.Any(c => c is '\r' or '\n' or '\0'))
            throw new InvalidOperationException("Zorin preseed values cannot contain line breaks or NUL characters.");
        return value;
    }

    private static string Decode(string content, string path) =>
        $"printf '%s' '{Convert.ToBase64String(Encoding.UTF8.GetBytes(content.Replace("\r\n", "\n")))}' | base64 -d > {path}";

