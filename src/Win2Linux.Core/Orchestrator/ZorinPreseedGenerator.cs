    private static string KernelScript(bool nvidia) => $$"""
        image=$(apt-cache pkgnames | grep -E '^linux-image-7\.3\.0-[0-9]+-generic$' | sort -V | tail -n 1)
        test -n "$image" || { echo 'The Ubuntu archive has no signed 7.3 generic image' >&2; exit 1; }
        release=${image#linux-image-}
        apt-get install -y --no-remove --no-install-recommends "$image" "linux-modules-$release" sbsigntool
        sbverify --list "/boot/vmlinuz-$release" > /tmp/win2linux-kernel-signature.txt
        grep -qi canonical /tmp/win2linux-kernel-signature.txt
        {{(nvidia ? NvidiaScript : "# No proprietary NVIDIA module requested")}}
        printf '%s\n' '# Lenovo Legion CS35L41 routing' 'options snd-hda-intel model=dual-codecs' 'options snd-sof-pci-intel-tgl dmic_detect=0' > /etc/modprobe.d/alsa-legion-speakers.conf
        update-initramfs -u -k "$release"
        mkdir -p /var/lib/win2linux
        printf '%s\n' "$release (Ubuntu Stonking, Canonical-signed)" > /var/lib/win2linux/kernel-7.3-installed
        """;

    private const string NvidiaScript = """
        # Select a GPU-compatible Zorin driver with a matching signed module for this ABI.
        matched=0
        while read -r driver; do
            [[ "$driver" =~ ^nvidia-driver-[0-9]+(-open)?$ ]] || continue
            module="linux-modules-${driver/-driver/}-$release"
            branch=${driver#nvidia-driver-}; branch=${branch%-open}
            # Noble's desktop metapackage requires DKMS. Pair its userspace
            # components with the no-DKMS package and the signed prebuilt module.
            userspace=("${driver/nvidia-driver/nvidia-headless-no-dkms}" "libnvidia-gl-$branch" "libnvidia-extra-$branch" "libnvidia-decode-$branch" "libnvidia-encode-$branch" "libnvidia-fbc1-$branch" "nvidia-utils-$branch" "xserver-xorg-video-nvidia-$branch" nvidia-settings nvidia-prime)
            if apt-cache show "$module" >/dev/null 2>&1 && apt-get -s --no-remove --no-install-recommends install "$module" "${userspace[@]}" >/dev/null 2>&1; then
                apt-get install -y --no-remove --no-install-recommends "$module" "${userspace[@]}"
                modinfo -k "$release" -F signer nvidia | grep -qi canonical
                module_version=$(modinfo -k "$release" -F version nvidia)
                userspace_version=$(dpkg-query -W -f='${Version}' "nvidia-kernel-common-$branch")
                test "$module_version" = "${userspace_version%%-*}"
                matched=1
                break
            fi
        done < <(ubuntu-drivers list --include-dkms | sed 's/[,[:space:]].*$//' | sort -Vu -r)
        test "$matched" = 1 || { echo 'No compatible signed NVIDIA module/driver pair is available for the requested 7.3 kernel' >&2; exit 1; }
        """;
